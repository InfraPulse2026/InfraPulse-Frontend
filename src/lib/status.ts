export function status(value?: string | null): [string, Tone] {
  return statuses[value?.toLowerCase() || 'unknown'] || [value || 'Неизвестно', 'muted'];
}
export function can(permissions: readonly string[] | undefined, permission: string) {
  return permissions?.includes(permission) === true;
}
